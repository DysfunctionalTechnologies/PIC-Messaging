#DEFINE  _MAIN.ASM_
#INCLUDE Common.INC
;-------------------------------------------------------;

;-------------------------------------------------------;
MAIN_DATA         UDATA ; H'0020'
;-------------------------------------------------------;
SYSTEM_Flags1     res 1
SYSTEM_Flags2     res 1
Temp1             res 1
Temp2             res 1
;-------------------------------------------------------;

;-------------------------------------------------------;
_Reset_Vector     CODE H'0000'
;-------------------------------------------------------;
    CALL _Initialize_System
    GOTO _Main_Init
;-------------------------------------------------------;

;-------------------------------------------------------;
_Version_Number   CODE H'0002'
;-------------------------------------------------------;
    DW	VERSION_MAJOR
    DW	VERSION_MINOR
;-------------------------------------------------------;

;-------------------------------------------------------;
_Interrupt_Vector CODE H'0004'
;-------------------------------------------------------;
_IV_Entry:
    ;---------------------------------------------------;
#IF _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Timer_2_INT_Handler
    SKPNC
    GOTO    _IV_Entry
    ;---------------------------------------------------;
    CALL    _IR_INT_Handler
    SKPNC
    GOTO    _IV_Entry
    ;---------------------------------------------------;
#ENDIF ; _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Timer_0_INT_Handler
    SKPNC
    GOTO    _IV_Entry
    ;---------------------------------------------------;
    RETFIE
;-------------------------------------------------------;

;-------------------------------------------------------;
MAIN_CODE CODE ; H'0020'
;-------------------------------------------------------;

;-------------------------------------------------------;
_Main_Init:
;-------------------------------------------------------;
;-------------------------------------------------------;
_Main:
;-------------------------------------------------------;
#IF _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Process_Remote_Code
    ;---------------------------------------------------;
#ENDIF ; _IR_ENABLED_    
    ;---------------------------------------------------;
    BTFSS   TIMER_0_INT_FLAG
    GOTO    _Main
    BCF     TIMER_0_INT_FLAG
    ;---------------------------------------------------;
    BTFSS   EE_GLASS_FLAG
    ;---------------------------------------------------;
    CALL    _Update_Messaging
    ;---------------------------------------------------;
    GOTO    _Main
;-------------------------------------------------------;

;-------------------------------------------------------;
_Initialize_System:
;-------------------------------------------------------;
    ; Initialize System Flags
    ;---------------------------------------------------;
    BANKSEL MEMORY
    CLRF    SYSTEM_Flags1
    BSF	    POWER_FLAG
    CLRF    SYSTEM_Flags2
    ;---------------------------------------------------;

    ;---------------------------------------------------;
    ; Initialize Hardware Subsystems
    ;---------------------------------------------------;
    CALL    _Init_Microcontroller
    ;---------------------------------------------------;
    PAGESEL _Init_Himem_Subsystem
    CALL	_Init_Himem_Subsystem
    PAGESEL $
    ;---------------------------------------------------;
    CALL    _Init_EEPROM_Subsystem
    CALL    _Init_Timer_0_Subsystem
    CALL    _Init_MAX7219_Subsystem
    CALL    _Init_Font_Subsystem
    ;---------------------------------------------------;
    CALL    _Init_I2C_Subsystem
    ;---------------------------------------------------;
#IF _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Init_Timer_2_Subsystem
    CALL    _Init_IR_Subsystem
    CALL    _Init_Remote_Subsystem
    ;---------------------------------------------------;
#ENDIF ; _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Init_Messaging_Subsystem
    ;---------------------------------------------------;

    ;---------------------------------------------------;
    ; Initialize Variables
    ;---------------------------------------------------;
    BANKSEL MEMORY
    ;---------------------------------------------------;
    ; Start Running
    ;---------------------------------------------------;
    TURN_ON_INTS_M
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
    END
;-------------------------------------------------------;
