_IV_Entry:
    ;---------------------------------------------------;
#IF _IR_ENABLED_    
    ;---------------------------------------------------;
    CALL    _Timer_2_INT_Handler
    SKPNC
    GOTO    _IV_Entry
    ;---------------------------------------------------;
    CALL    _IR_INT_Handler
    SKPNC
    GOTO    _IV_Entry
    ;---------------------------------------------------;
