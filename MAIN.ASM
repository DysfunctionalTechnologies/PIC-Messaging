    BTFSS   TIMER_0_INT_FLAG
    GOTO    _Main
    BCF     TIMER_0_INT_FLAG
    BTFSC   EE_GLASS_FLAG
    GOTO    _Main              ; leave EE text alone
    CALL    _Update_Messaging
