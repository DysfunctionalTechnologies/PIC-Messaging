IR_CODE CODE
;-------------------------------------------------------;

;-------------------------------------------------------;
_IR_INT_Handler:
;-------------------------------------------------------;
    BANKSEL INTCON
    BTFSC   INTCON, IOCIF
    GOTO    _IRIH_Entry
    BCF     STATUS, C
    RETURN
    ;---------------------------------------------------;
_IRIH_Entry:
    ;---------------------------------------------------;
    CALL    _Process_IR_Stream
    ;---------------------------------------------------;
_IRIH_Exit:
    ;---------------------------------------------------;
    BANKSEL IOCAF
    CLRF    IOCAF
    ;---------------------------------------------------;
    BANKSEL INTCON
    BCF     INTCON, IOCIF
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Process_IR_Stream:
;-------------------------------------------------------;
    CALL    _Save_And_Reset_Timer_2
    ;---------------------------------------------------;
    ; Already have a valid code?
    ;---------------------------------------------------;
    BTFSC   IR_CODE_VALID_FLAG
    ;---------------------------------------------------;
    ; Yes, exit
    ;---------------------------------------------------;
    RETURN
    ;---------------------------------------------------;
    ; Are we processing data bits?
    ;---------------------------------------------------;
    BTFSC   IR_PROCESSING_FLAG
    ;---------------------------------------------------;
    ; Yes, check data pulse
    ;---------------------------------------------------;
    GOTO    _PIRS_Check_Data
    BSF     IR_BLOCK_FLAG
    ;---------------------------------------------------;
_PIRS_Check_Preamble:
    ;---------------------------------------------------;
    MOVLW   H'40'
    SUBWF   Timer_2_Overflow, W
    SKPC
    GOTO    _PIRS_Error
    MOVLW   H'F0'
    SUBWF   Timer_2_Overflow, W
    SKPNC
    GOTO    _PIRS_Error
    ;---------------------------------------------------;
_PIRS_Preamble:
    ;---------------------------------------------------;
    ; Valid preamble, now we are processing bits
    ;---------------------------------------------------;
    BSF     IR_PROCESSING_FLAG
    ;---------------------------------------------------;
    ; Clear received codes
    ;---------------------------------------------------;
    CLRF    IR_Code_0
    CLRF    IR_Code_1
    CLRF    IR_Code_2
    CLRF    IR_Code_3
    ;---------------------------------------------------;
    ; 32 bits to receive
    ;---------------------------------------------------;
    MOVLW   32
    MOVWF   IR_Code_Bit_Count
    RETURN
    ;---------------------------------------------------;
_PIRS_Check_Data:
    ;---------------------------------------------------;
    ; Data Bit
    ; Under 08 is error
    ;---------------------------------------------------;
    MOVLW   H'08'
    SUBWF   Timer_2_Overflow, W
    SKPC
    GOTO    _PIRS_Error
    ;---------------------------------------------------;
    ; Data Bit 0 - between 08-17
    ;---------------------------------------------------;
    MOVLW   H'18'
    SUBWF   Timer_2_Overflow, W
    SKPC
    GOTO    _PIRS_Data_0
    ;---------------------------------------------------;
    ; Data Bit 1 - between 20-2F
    ;---------------------------------------------------;
    MOVLW   H'28'
    SUBWF   Timer_2_Overflow, W
    SKPNC
    GOTO    _PIRS_Error
    ;---------------------------------------------------;
_PIRS_Data_1:
    ;---------------------------------------------------;
    ; C=1, RRed into MSB of RC_Code_3
    ;---------------------------------------------------;
    BSF     STATUS, C
    GOTO    _PIRS_Process_Bit
    ;---------------------------------------------------;
_PIRS_Data_0:
    ;---------------------------------------------------;
    ; C=0, RRed into MSB of RC_Code_3
    ;---------------------------------------------------;
    BCF     STATUS, C
    ;---------------------------------------------------;
_PIRS_Process_Bit:
    ;---------------------------------------------------;
    ; NOP_CODE OP_CODE  DEV_CODE MFG_CODE
    ; (CODE_3) (CODE_2) (CODE_1) (CODE_0)
    ; 33222222 22221111 11111100 00000000
    ; 10987654 32109876 54321098 76543210
    ; RR RC_Code_3, C into MSB, LSB into C
    ;---------------------------------------------------;
    RRF     IR_Code_3, F
    ;---------------------------------------------------;
    ; RR RC_Code_2, C into MSB, LSB into C
    ;---------------------------------------------------;
    RRF     IR_Code_2, F
    ;---------------------------------------------------;
    ; RR RC_Code_1, C into MSB, LSB into C
    ;---------------------------------------------------;
    RRF     IR_Code_1, F
    ;---------------------------------------------------;
    ; RR RC_Code_0, C into MSB, LSB into C
    ;---------------------------------------------------;
    RRF     IR_Code_0, F
    ;---------------------------------------------------;
    ; Decrement bit count - all 32 bits processed?
    ;---------------------------------------------------;
    DECFSZ  IR_Code_Bit_Count, F
    RETURN
    ;---------------------------------------------------;
_PIRS_Check_Code_Valid:        ; All 32 bits of data processed
    ;---------------------------------------------------;
    ; Op/NOp codes
    ;---------------------------------------------------;
    MOVFW   IR_Code_3
    ;---------------------------------------------------;
    ; Inverse of each other?
    ;---------------------------------------------------;
    XORWF   IR_Code_2, W
    XORLW   H'FF'
    SKPZ
    ;---------------------------------------------------;
    ; No, error
    ;---------------------------------------------------;
    GOTO    _PIRS_Error
    ;---------------------------------------------------;
_PIRS_Code_Valid:
    ;---------------------------------------------------;
    ; 1st code is Manufacturer code (Mfg_Code)
    ;---------------------------------------------------;
    MOVFW   IR_Code_0
    MOVWF   IR_Mfg_Code
    ;---------------------------------------------------;
    ; 2nd code is Device code (Dev_Code)
    ;---------------------------------------------------;
    MOVFW   IR_Code_1
    MOVWF   IR_Dev_Code
    ;---------------------------------------------------;
    ; 3rd code is Operation code (Op_Code)
    ;---------------------------------------------------;
    MOVFW   IR_Code_2
    MOVWF   IR_Op_Code
    ;---------------------------------------------------;
    ; Processing done, clear flag
    ;---------------------------------------------------;
    BCF     IR_PROCESSING_FLAG
    ;---------------------------------------------------;
    ; Flag a valid RC Code
    ;---------------------------------------------------;
    BSF     IR_CODE_VALID_FLAG
    RETURN
    ;---------------------------------------------------;
_PIRS_Error:
    ;---------------------------------------------------;
    ; Clear Processing flag
    ;---------------------------------------------------;
    BCF     IR_PROCESSING_FLAG
    ;---------------------------------------------------;
    ; Clear valid RC Code flag
    ;---------------------------------------------------;
    BCF     IR_CODE_VALID_FLAG
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Initialize_IR_Subsystem:
;-------------------------------------------------------;
    ; Initialize I/O Port (Interrupt)
    ;---------------------------------------------------;
    BANKSEL IR_DIR
    BSF     IR_DIR, IR_BIT
    ;---------------------------------------------------;
    ; Initialize External Interrupt
    ;---------------------------------------------------;
    BANKSEL OPTION_REG
    BCF	    OPTION_REG, INTEDG ; IR is neg-edge triggered
    ;---------------------------------------------------;
    ; Enable Interrupts
    ;---------------------------------------------------;
    BANKSEL IOCAP
    CLRF    IOCAP
    BANKSEL IOCAN
    CLRF    IOCAN
    BSF     IOCAN, IR_BIT
    BANKSEL IOCAF
    CLRF    IOCAF
    BANKSEL INTCON
    BSF     INTCON, IOCIE
    BSF     INTCON, PEIE
    ;---------------------------------------------------;
    ; Initialize Variables
    ;---------------------------------------------------;
    BANKSEL MEMORY
    CLRF    IR_Mfg_Code
    CLRF    IR_Dev_Code
    CLRF    IR_Op_Code
    CLRF    IR_Status
    RETURN
