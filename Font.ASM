#DEFINE  _FONT.ASM_
#INCLUDE Common.INC
;-------------------------------------------------------;

;-------------------------------------------------------;
FONT_CODE CODE
;-------------------------------------------------------;

;-------------------------------------------------------;
_Reset_Font_Ptr:
;-------------------------------------------------------;
    MOVLW   HIGH _Font_Table
    IORLW   H'80'
    MOVWF   Font_Ptr_HI
    ;---------------------------------------------------;
    MOVLW   LOW  _Font_Table
    MOVWF   Font_Ptr_LO
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Reset_Font:
;-------------------------------------------------------;
    CALL    _Reset_Font_Ptr
    CLRF    Font_Line_Ptr
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Set_Font_Ptr:
;-------------------------------------------------------;
    MOVFW   Font_Ptr_LO
    MOVWF   FSR1L
    MOVFW   Font_Ptr_HI
    MOVWF   FSR1H
    MOVFW   Font_Line_Ptr
    ADDWF   FSR1L, F
    SKPNC
    INCF    FSR1H, F
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Set_Font_Line_Ptr:
;-------------------------------------------------------;
    ADDLW   1
    MOVWF   Font_Line_Ptr
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Next_Font_Char:
;-------------------------------------------------------;
    MOVLW   MAX_LINES + 1
    ADDWF   Font_Ptr_LO, F
    SKPNC
    INCF    Font_Ptr_HI, F
    CLRF    Font_Line_Ptr
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Next_Font_Line:
;-------------------------------------------------------;
    INCF    Font_Line_Ptr, F
    MOVLW   MAX_LINES + 1
    XORWF   Font_Line_Ptr, W
    SKPZ
    ;---------------------------------------------------;
    RETURN
    ;---------------------------------------------------;
    MOVLW   1
    MOVWF   Font_Line_Ptr
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Set_Font_Line:
;-------------------------------------------------------;
    ADDLW   1
    MOVWF   Font_Line_Ptr
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Get_Data_From_Font:
;-------------------------------------------------------;
    CALL    _Set_Font_Ptr
    MOVFW   INDF1
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Find_Char_In_Font:
;-------------------------------------------------------;
    MOVWF   Char_To_Find
    CALL    _Reset_Font
    ;---------------------------------------------------;
_GDFC_Next:
    ;---------------------------------------------------;
    CALL    _Get_Data_From_Font
    XORLW   H'FF'
    SKPNZ
    GOTO    _GDFC_Not_Found
    CALL    _Get_Data_From_Font
    XORWF   Char_To_Find, W
    SKPNZ
    GOTO    _GDFC_Found
    CALL    _Next_Font_Char
    GOTO    _GDFC_Next
    ;---------------------------------------------------;
_GDFC_Not_Found:
    ;---------------------------------------------------;
    CALL    _Reset_Font
    ;---------------------------------------------------;
_GDFC_Found:
    ;---------------------------------------------------;
    CALL    _Next_Font_Line
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
_Initialize_Font_Subsystem:
;-------------------------------------------------------;
    ;---------------------------------------------------;
    RETURN
;-------------------------------------------------------;

;-------------------------------------------------------;
    END
;-------------------------------------------------------;

