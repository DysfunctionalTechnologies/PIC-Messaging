_Process_Remote_Code:
;-------------------------------------------------------;
    BTFSS   IR_CODE_VALID_FLAG
    RETURN
    ; Ubiquitous Chinese Remote has a MFG code of H'00'
    ; If not H'00', code is invalid for this system
    ;---------------------------------------------------;
    MOVLW   H'00'
    XORWF   IR_Mfg_Code, W
    SKPZ
    GOTO    _Remote_Code_Done
    ;---------------------------------------------------;
    ; Ubiquitous Chinese Remote has a DEV code of H'EF'
    ; If not H'EF', code is invalid for this system
    ;---------------------------------------------------;
    MOVLW   H'EF'
    XORWF   IR_Dev_Code, W
    SKPZ
    GOTO    _Remote_Code_Done
    ;---------------------------------------------------;
    ; Ubiquitous Chinese Remote has a MFG code of H'00'
    ; If not H'00', code is invalid for this system
    ;---------------------------------------------------;
    MOVLW   H'18'
    SUBWF   IR_Op_Code, W
    SKPNC
    GOTO    _Remote_Code_Done
    MOVFW   IR_Op_Code
    BRW
    ;---------------------------------------------------;
    GOTO    _Remote_Code_00_EF_00
    GOTO    _Remote_Code_00_EF_01
    GOTO    _Remote_Code_00_EF_02
    GOTO    _Remote_Code_00_EF_03
